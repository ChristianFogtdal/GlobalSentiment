-- is NOT assumed; grants observed showed no explicit GRANT rows for
-- service_role on post_analyses beyond default ownership. No additional
-- GRANT statements are required to reproduce the observed state, since
-- table owner (postgres) already has full privileges by default.

grant select on public.completed_post_analyses to anon;
grant select on public.completed_post_analyses to authenticated;
